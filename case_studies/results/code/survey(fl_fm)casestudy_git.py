@torch.no_grad()
def evaluate_acc(model, dataset):
    model.eval()
    loader = DataLoader(dataset, batch_size=256, shuffle=False, num_workers=2)
    correct = 0; total = 0
    for x, y in loader:
        x, y = x.to(device), y.to(device)
        logits = model(x)
        pred = logits.argmax(dim=1)
        correct += (pred == y).sum().item()
        total += y.numel()
    return correct / total

