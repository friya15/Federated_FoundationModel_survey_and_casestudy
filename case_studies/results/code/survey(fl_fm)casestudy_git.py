@torch.no_grad()
def per_sample_losses(model, dataset, indices, bs=128):
    loader = DataLoader(Subset(dataset, indices), batch_size=bs, shuffle=False, num_workers=2)
    out = []
    for x, y in loader:
        x, y = x.to(device), y.to(device)
